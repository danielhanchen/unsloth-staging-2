def check_sha(sha: str) -> str:
    if not re.fullmatch(r"[0-9a-f]{40}", sha or ""):
        raise SystemExit(f"--base-sha must be a full 40-hex unsloth commit, got {sha!r}")
    return sha


def render_linux(doc: dict, base_sha: str, bline_ref: str, fa_sha: str = DEFAULT_FA_SHA) -> str:
    check_sha(base_sha)
    if not bline_ref:
        raise SystemExit("--bline-ref is required")
    jobs = doc["jobs"]
    title = doc.get("title") or doc["branch"]
    text = HEADER.format(title = title, base_short = base_sha[:12], bline_ref = bline_ref, branch = doc["branch"],
                         base_sha = base_sha, fa_sha = fa_sha)
    trial = next((j["id"] for j in jobs if j.get("trial")), None)
    prev = None
    for j in jobs:
        if j.get("criteria", "no_regression") == "differential" and not j.get("defect"):
            raise SystemExit(f"job {j['id']}: criteria differential needs a defect (the VOID rule)")
        budget = float(j.get("budget_min", 420))
        pa = ["--spec", j["spec"], "--budget-min", f"{budget:g}", "--cell-timeout", f"{float(j.get('cell_timeout', 3600)):g}"]
        for o in j.get("only") or []:
            pa += ["--only", o]
        for h in j.get("head_only") or []:
            pa += ["--state-only", f"head={h}"]
        if j.get("defect"):
            pa += ["--defect", j["defect"]]
        if prev is None:
            needs = ""
        elif prev == trial:
            needs = f"    needs: [{trial}]\n"
        elif trial:
            needs = (f"    needs: [{trial}, {prev}]\n"
                     f"    if: ${{{{ always() && needs.{trial}.result == 'success' }}}}\n")
        else:
            needs = f"    needs: [{prev}]\n    if: ${{{{ always() }}}}\n"
        patch = j.get("patch") or MARKER_PATCH
        bp = j.get("base_patch")
        base_patch_cmd = ""
        if bp:
            base_patch_cmd = (f'          git -C "$AMD_CI_WORK/states/base" apply --index '
                              f'"$GITHUB_WORKSPACE/amd_ci/patches/{bp}"\n')
        fx = ""
        if j.get("fixture"):
            fx = ("\\\n            --fixture diffusion_bench/amd/hold_to_free.py "
                  + " ".join(f"--fixture-arg={shlex.quote(x)}" for x in j["fixture"]) + " --fixture-timeout 900 ")
        extra = FETCH_STEP.format(spec = j["spec"]) if j.get("fetch_files", True) else ""
        text += JOB.format(jid = j["id"], title = j.get("title", j["id"]), needs = needs, patch = patch,
                           base_patch_cmd = base_patch_cmd, extra_steps = extra,
                           preflight_gib = j.get("preflight_gib", 50), criteria = j.get("criteria", "no_regression"),
                           fixture = fx, probe_args = " ".join(shlex.quote(a) for a in pa),
                           harness_env = HARNESS_ENV_BASH, step_timeout = int(budget * 2 + 45),
                           job_timeout = min(600, int(budget * 2 + 240)))
        prev = j["id"]
    return text


def harden_windows(text: str, step_timeout_min: int = 360) -> str:
    """The amd_ci Windows template's Differential step, with the harness env asserted, the profiler off, a step
    timeout, and an always() stop step that kills whatever is left under AMD_CI_WORK."""
    anchor = '      - name: Differential\n        run: |\n          $ErrorActionPreference = "Continue"\n'
    if anchor not in text:
        raise SystemExit("the Windows template's Differential step moved; update gen_workflow.harden_windows")
    text = text.replace(anchor, f'      - name: Differential\n        timeout-minutes: {step_timeout_min}\n'
                                '        run: |\n          $ErrorActionPreference = "Continue"\n' + HARNESS_ENV_PS, 1)
    up = "\n      - uses: actions/upload-artifact@v4\n"
    i = text.rfind(up)
    if i < 0:
        raise SystemExit("no upload-artifact step in the Windows workflow")
    return text[:i] + STOP_PS + text[i:]


def harden_linux_template(text: str, step_timeout_min: int = 360) -> str:
    """The same invariants for an amd_ci/scaffold.py Linux workflow (the --pr route)."""
    anchor = "      - name: Differential\n        run: |\n          set +e\n"
    if anchor not in text:
        raise SystemExit("the Linux template's Differential step moved; update gen_workflow.harden_linux_template")
    return text.replace(anchor, f"      - name: Differential\n        timeout-minutes: {step_timeout_min}\n"
                                "        run: |\n          set +e\n" + HARNESS_ENV_BASH, 1)


GENERATED_MARK = "# Generated by diffusion_bench/amd/gen_workflow.py"
# Words a workflow pushed to a public fork must not carry (names, comments, paths, log lines): the baseline UI is
# "baseline" there. selftest_amd greps every generated workflow for them.
PUBLIC_FORBIDDEN = re.compile(r"bline", re.IGNORECASE)


def with_baseline_repo(text: str) -> str:
    """An amd_ci template workflow with BASELINE_REPO (the repository variable) added to its top-level env."""
    if "BASELINE_REPO:" in text or "\nenv:\n" not in text:
        return text
    return text.replace("\nenv:\n", "\nenv:\n  BASELINE_REPO: ${{ vars.BASELINE_REPO }}\n", 1)


def public_problems(text: str) -> list:
    """Lines of a generated workflow that name the baseline UI (must be empty before a public push)."""
    return [f"{i}: {ln.strip()[:120]}" for i, ln in enumerate(text.splitlines(), 1) if PUBLIC_FORBIDDEN.search(ln)]


def write(out: Path, branch: str, text: str) -> Path:
    """Write the workflow (refused when it names the baseline UI). Replaces only workflows THIS generator wrote
    (carrying GENERATED_MARK) in OUT/.github/workflows: a checkout's own workflows are never deleted."""
    bad = public_problems(text)
    if bad:
        raise SystemExit(f"generated workflow names the baseline UI (public fork): {bad[:5]}")
    wf = out / ".github" / "workflows" / f"{branch}.yml"
    wf.parent.mkdir(parents = True, exist_ok = True)
    for old in wf.parent.glob("*.yml"):
        if old != wf and GENERATED_MARK in old.read_text(encoding = "utf-8", errors = "replace"):
            old.unlink()
    wf.write_text(text, encoding = "utf-8")
    patches = out / "amd_ci" / "patches"
    patches.mkdir(parents = True, exist_ok = True)
    (patches / MARKER_PATCH).write_text(MARKER_TEXT, encoding = "utf-8")
    return wf


def main() -> int:
    ap = argparse.ArgumentParser(description = __doc__, formatter_class = argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--jobs", required = True, type = Path)
    ap.add_argument("--out", required = True, type = Path)
    ap.add_argument("--base-sha", required = True)
    ap.add_argument("--bline-ref", required = True)
    ap.add_argument("--fa-sha", default = DEFAULT_FA_SHA)
    a = ap.parse_args()
    doc = json.loads(a.jobs.read_text())
    wf = write(a.out, doc["branch"], render_linux(doc, a.base_sha, a.bline_ref, a.fa_sha))
    print(f"wrote {wf}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
