#!/usr/bin/env python3
"""One generic gfx1151 workflow generator (replaces gen_nov5_workflow.py and gen_studio_vs_bline_workflow.py).

  python diffusion_bench/amd/gen_workflow.py --jobs JOBS.json --out DIR --base-sha SHA --bline-ref TAG
  (plan route: amd/scaffold_diffusion.py --plan PLAN.json --vm amd-gfx1151-linux-1 --out DIR)

Nothing is pinned in this file: the unsloth base commit (--base-sha, a full 40-hex SHA) and the BlineUI ref come
from the caller or the plan's revisions. JOBS.json:
  {"branch": "amd-ci-dbench-...", "jobs": [
     {"id": "t0_trial", "title": "...", "spec": "diffusion_bench/specs/x.json", "only": ["glob"],
      "head_only": ["tag"],              # cells the head state re-runs (an extra A/A point when head = base + marker)
      "criteria": "no_regression",       # | differential (then "defect" is required)
      "defect": null, "patch": null,     # null = head is base + a no-op marker file (measurement job)
      "base_patch": null, "fixture": null, "preflight_gib": 50, "fetch_files": true, "pt72": false,
      "budget_min": 420, "cell_timeout": 3600, "trial": false}]}

Every job, Linux (generated here) and Windows (amd_ci template, hardened by harden_windows()):
  - asserts TORCH_ROCM_AOTRITON_ENABLE_EXPERIMENTAL=1 in the measuring step (exported, then checked in bash AND in
    the job's Python, exit 3 when missing): without it SDPA on gfx1151 falls back to the math kernel;
  - unsets CI (CI=true on the runners flips a functorch aliasing check) and checks it is gone;
  - Windows: DBENCH_NO_PROFILER=1 (the torch profiler hangs the Windows ROCm runtime; fa_smoke honours it);
  - kills arms that never exit: --cell-timeout per cell (matrix kills the process group), a step timeout of
    budget + 45 min on the measuring step, and an always() step that TERMs then KILLs whatever is left under
    $AMD_CI_WORK (Windows: every process whose command line names it).
Measurement only: no secret is referenced; models are public downloads.
"""

