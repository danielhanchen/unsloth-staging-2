"""local:B200: parity and quality only (a shared host GPU never gives a timing). Cells run through matrix.py
--plan --vm under gpu_queue.py (a shared lease sized by --gb), never --exclusive.

  python -m targets.local prepare PLAN.json --out DIR [--gb 60]
  python -m targets.local collect DIR/runs/<vm_id> [--plan PLAN.json]
"""

from __future__ import annotations

import argparse
import json
import shlex
import sys
from pathlib import Path

from . import common as TC


def refuse_timing(plan: dict) -> None:
    bad = []
    for vm in TC.vms_of(plan, "local"):
        if vm.get("purpose") == "timing":
            bad.append(vm["vm_id"])
        cells = {c["tag"]: c for c in plan["cells"]}
        for slot in vm["slots"]:
            for it in slot:
                arm = (cells[it["tag"]].get("options") or {}).get("arm") or {}
                if it.get("timed") or arm.get("purpose") == "timing":
                    bad.append(it["tag"])
    if bad:
        raise SystemExit(f"local:B200 refuses timing arms (parity / quality only): {bad[:8]}")


def prepare(plan: dict, out_dir, gb: float = 60.0, plan_path: str | None = None, **_) -> dict:
    refuse_timing(plan)
    out_dir = Path(out_dir)
    vms = TC.vms_of(plan, "local")
    if not vms:
        return {"kind": "local", "vms": []}
    out_dir.mkdir(parents = True, exist_ok = True)
    pp = Path(plan_path) if plan_path else out_dir / "plan.json"
    if not plan_path:
        pp.write_text(json.dumps(plan, indent = 1))
    rev = TC.toolkit_revision()
    lines = ["#!/usr/bin/env bash", "# Generated by diffusion_bench targets (local). Parity / quality only: no timing.",
             f"# toolkit {rev['sha']}{' (dirty)' if rev['dirty'] else ''}", "set -u",
             'WORKSPACE="${WORKSPACE:?set WORKSPACE}"', 'TK="$(cd "$(dirname "$0")" && pwd)"']
    lines.append(f'python {shlex.quote(str(TC.TOOLKIT / "targets" / "fetch_files.py"))} --spec {shlex.quote(str(pp))} '
                 '--root "$WORKSPACE/temp/dbench_cm" --write "$TK/plan_resolved.json" || exit 1')
    for vm in vms:
        est = max(5, int(vm["est_min"]))
        lines.append(f'python "$WORKSPACE/gpu_queue.py" run --gb {gb:g} --est-min {est} --what {shlex.quote(vm["vm_id"])} -- '
                     f'python {shlex.quote(str(TC.TOOLKIT / "matrix.py"))} --plan "$TK/plan_resolved.json" --vm {vm["vm_id"]} '
                     f'--out "$TK/runs/{vm["vm_id"]}"')
    sh = out_dir / "run_local.sh"
    sh.write_text("\n".join(lines) + "\n")
    sh.chmod(0o755)
    meta = {"kind": "local", "vms": [v["vm_id"] for v in vms], "launch": str(sh), "plan": str(pp),
            "scripts_sha": rev["sha"], "dirty": rev["dirty"]}
    (out_dir / "prepared_local.json").write_text(json.dumps(meta, indent = 1))
    return meta


def collect(run_dir, plan=None) -> list:
    return TC.collect_records(Path(run_dir), "local:B200", plan)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description = __doc__, formatter_class = argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest = "cmd", required = True)
    p = sub.add_parser("prepare")
    p.add_argument("plan")
    p.add_argument("--out", required = True)
    p.add_argument("--gb", type = float, default = 60.0)
    c = sub.add_parser("collect")
    c.add_argument("run_dir")
    c.add_argument("--plan", help = "PLAN.json: copy its cases.json into run_dir (report.py's expected case set)")
    a = ap.parse_args(argv)
    if a.cmd == "prepare":
        print(json.dumps(prepare(json.loads(Path(a.plan).read_text()), a.out, gb = a.gb, plan_path = a.plan), indent = 1))
    else:
        print(json.dumps([{"tag": r.get("tag"), "verdict": r.get("verdict")} for r in collect(a.run_dir, a.plan)], indent = 1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
