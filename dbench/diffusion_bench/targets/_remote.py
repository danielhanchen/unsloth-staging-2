"""Shared prepare / collect for the notebook targets (colab, kaggle): one toolkit bundle per plan, one notebook per
VM, one launch script."""

from __future__ import annotations

import json
import re
import shlex
from pathlib import Path

from . import common as TC
from . import notebook as NB

# Token shapes a run must never leave in its files (the executed notebook comes back): Hugging Face, GitHub classic /
# OAuth / app / refresh tokens and fine-grained PATs, Kaggle API tokens and a kaggle.json key (secret_scrub.py's
# shapes); plus the literal values of the token variables in this shell (collect_leaks).
TOKEN_RE = re.compile(rb"hf_[A-Za-z0-9]{30,}|\bgh[pousr]_[A-Za-z0-9]{36,255}\b|\bgithub_pat_[A-Za-z0-9_]{60,255}\b"
                      rb"|\bKGAT_[A-Za-z0-9]{24,}\b|\"key\"\s*:\s*\"[0-9a-f]{32}\"")
TOKEN_ENV = ("HF_TOKEN", "HUGGING_FACE_HUB_TOKEN", "GH_TOKEN", "GITHUB_TOKEN", "KAGGLE_KEY", "KAGGLE_API_TOKEN")


def prepare(plan: dict, out_dir: Path, kind: str, launch_line, unsloth_sha: str | None = None,
            bline_ref: str | None = None, account: str | None = None, workspace: str | None = None,
            allow_dirty: bool = False, hf_token: bool = True, vm_ids: list | None = None,
            zoo_sha: str | None = None, bline_gguf_sha: str | None = None) -> dict:
    out_dir = Path(out_dir)
    vms = [v for v in TC.vms_of(plan, kind) if not vm_ids or v["vm_id"] in vm_ids]
    if not vms:
        return {"kind": kind, "vms": [], "note": f"plan has no {kind} VM"}
    rev = dict(plan.get("revisions") or {})
    rev.update({k: v for k, v in (("unsloth_sha", unsloth_sha), ("bline_ref", bline_ref), ("zoo_sha", zoo_sha)) if v})
    for key, url in (("unsloth_sha", UNSLOTH_URL), ("zoo_sha", ZOO_URL)):
        if rev.get(key):
            rev[key] = resolve_ref(url, rev[key])
    NB.check_revisions(rev)
    cells = [c for vm in vms for c in TC.vm_slice(plan, vm["vm_id"])["cells"].values()]
    if bline_gguf_sha:
        rev["bline_gguf_sha"] = bline_gguf_sha
    if NB.needs_gguf_node(cells):
        # the GGUF loader node is pinned like every other revision (its main, resolved now, unless one is given)
        rev["bline_gguf_sha"] = resolve_ref(GGUF_NODE_URL, rev.get("bline_gguf_sha") or "main")
        if not re.fullmatch(r"[0-9a-f]{40}", str(rev["bline_gguf_sha"])):
            raise SystemExit(f"baseline GGUF cells need the GGUF loader node at a commit; could not resolve "
                             f"{rev['bline_gguf_sha']!r} ({GGUF_NODE_URL}): pass --bline-gguf-sha SHA")
    bundle = TC.build_bundle(out_dir / "bundle", allow_dirty = allow_dirty, kit = TC.needs_kit(cells))
    rev["scripts_sha"] = bundle["scripts_sha"]
    data = Path(bundle["path"]).read_bytes()
    nbs, lines = {}, []
    for vm in vms:
        sl = TC.vm_slice(plan, vm["vm_id"])
        sl["revisions"] = rev
        nb = NB.build(sl, data, bundle, rev, kind)
        nbs[vm["vm_id"]] = str(NB.write(nb, out_dir / "nb" / f"{vm['vm_id']}.ipynb"))
        (out_dir / "slices").mkdir(parents = True, exist_ok = True)
        (out_dir / "slices" / f"{vm['vm_id']}.json").write_text(json.dumps(sl, indent = 1))
        lines.append((vm, launch_line(vm, f"nb/{vm['vm_id']}.ipynb", f"runs/{vm['vm_id']}", account, hf_token)))
    launch = out_dir / f"launch_{kind}.sh"
    launch.write_text(launch_script(kind, lines, workspace))
    launch.chmod(0o755)
    meta = {"kind": kind, "revisions": rev, "bundle": bundle, "notebooks": nbs, "launch": str(launch),
            "vms": [v["vm_id"] for v in vms], "plan_sha256": TC.plan_digest(plan)}
    (out_dir / f"prepared_{kind}.json").write_text(json.dumps(meta, indent = 1))
    return meta


UNSLOTH_URL = "https://github.com/unslothai/unsloth"
ZOO_URL = "https://github.com/unslothai/unsloth-zoo"
GGUF_NODE_URL = "https://github.com/city96/BlineUI-GGUF"


def resolve_ref(url: str, ref: str) -> str:
    """A full 40-hex commit as is; a branch / tag (``main``) -> the commit it points at NOW (git ls-remote), so the
    plan records the revision every VM installs, not a moving name. Unresolvable -> the input (check_revisions
    then refuses it)."""
    ref = str(ref).strip()
    if re.fullmatch(r"[0-9a-f]{40}", ref):
        return ref
    import subprocess  # noqa: PLC0415

    try:
        out = subprocess.run(["git", "ls-remote", url, ref, f"refs/heads/{ref}", f"refs/tags/{ref}"],
                             capture_output = True, text = True, timeout = 60).stdout.split()
    except (OSError, subprocess.TimeoutExpired):
        return ref
    return out[0] if out and re.fullmatch(r"[0-9a-f]{40}", out[0]) else ref


def launch_script(kind: str, lines: list, workspace: str | None) -> str:
    ws = f'WORKSPACE="${{WORKSPACE:-{workspace}}}"' if workspace else 'WORKSPACE="${WORKSPACE:?set WORKSPACE}"'
    body = [
        "#!/usr/bin/env bash",
        f"# Generated by diffusion_bench targets ({kind}). usage: launch_{kind}.sh VM_ID [VM_ID ...] | all",
        "# One VM per notebook, each run in the foreground of this script (call it with run_in_background).",
        "# Tokens only via --env NAME (forwarded from this shell, never written into a notebook).",
        "# Why notebook_cloud_run.py and not cloud_pool.py / gpu_queue.py --exclusive: a comparison is defined on ONE",
        "# named tier (colab:L4 vs colab:A100-40 are different results); cloud_pool / gpu_queue pick the tier by VRAM",
        "# and cost and cannot pin it. Use cloud_pool for the cpu target (it has --cpu).",
        "set -u",
        ws,
        'HERE="$(cd "$(dirname "$0")" && pwd)"; cd "$HERE" || exit 1',
        'export CUDA_VISIBLE_DEVICES=""',
        "run_vm() {",
        '  case "$1" in',
    ]
    for vm, cmd in lines:
        body.append(f"    {vm['vm_id']}) {cmd} ;;")
    body += ['    *) echo "unknown vm $1"; return 2 ;;', "  esac", "}",
             f"ALL=({' '.join(vm['vm_id'] for vm, _ in lines)})",
             '[ "${1:-}" = all ] && set -- "${ALL[@]}"',
             '[ $# -ge 1 ] || { echo "usage: $0 VM_ID... | all  (VMs: ${ALL[*]})"; exit 2; }',
             'for VM in "$@"; do',
             '  echo "=== START $VM $(date -u +%FT%TZ) ==="',
             '  run_vm "$VM"; rc=$?',
             '  echo "=== DONE $VM rc=$rc $(date -u +%FT%TZ) ==="',
             "done",
             "echo '=== EXIT ==='", ""]
    return "\n".join(body)


def timeouts(vm: dict) -> tuple:
    """(wall, per-cell) seconds. The per-cell limit sits BELOW the wall one (a hung cell is cut before the VM's
    wall limit, leaving 10 min for the launcher to fetch what was written); never under 30 min."""
    wall = int(max(3600, min(40000, vm["est_min"] * 60 * 2.5)))
    return wall, max(1800, wall - 600)


def live_secrets() -> list:
    """The literal token values in this shell (HF_TOKEN, GH_TOKEN*, KAGGLE_KEY ...), 16+ chars, as bytes."""
    import os

    vals = {v for k, v in os.environ.items() if (k in TOKEN_ENV or k.startswith("GH_TOKEN_")) and v and len(v) >= 16}
    return [v.encode() for v in vals]


def leaks_in(data: bytes, secrets: list | None = None) -> bool:
    return bool(TOKEN_RE.search(data)) or any(s in data for s in (secrets if secrets is not None else live_secrets()))


def scan_leaks(run_dir: Path) -> None:
    """Refuse (raise) when a token shape or a live token value is in any file under run_dir. Callers unpack the
    artifacts FIRST, so a token inside artifact.tgz or a base64 block in a notebook / log is scanned too."""
    leaks = []
    secrets = live_secrets()
    for p in Path(run_dir).rglob("*"):
        if p.is_file() and not p.is_symlink() and p.stat().st_size < 512 * 2**20 and leaks_in(p.read_bytes(), secrets):
            leaks.append(str(p))
    if leaks:
        raise SystemExit(f"token-like string in {leaks[:5]}: scrub before reading / sharing these files")


def collect(run_dir: Path, target: str | None = None, plan=None) -> list:
    """Records under run_dir after unpacking the artifact; refuses (raises) when a token leaked into any file the
    run left behind (the executed notebook and the unpacked artifact included: TC.collect_records scans)."""
    return TC.collect_records(Path(run_dir), target, plan)


def q(s: str) -> str:
    return shlex.quote(s)


def env_flags(hf_token: bool) -> str:
    return "--env HF_TOKEN" if hf_token else ""

